// Language manager hook
export const useLanguage = (defaultLang = 'en') => {
  const [lang, setLang] = window.React?.useState
    ? window.React.useState(localStorage.getItem('language') || defaultLang)
    : [defaultLang]

  const t = (key, replacements = {}) => {
    let text = translations[lang]?.[key] || translations.en[key] || key
    
    // Replace placeholders like {name} with values
    Object.keys(replacements).forEach(placeholder => {
      text = text.replace(`{${placeholder}}`, replacements[placeholder])
    })
    
    return text
  }

  const toggleLanguage = () => {
    const newLang = lang === 'en' ? 'hi' : 'en'
    setLang(newLang)
    localStorage.setItem('language', newLang)
  }

  return { lang, t, toggleLanguage }
}

export default translations
